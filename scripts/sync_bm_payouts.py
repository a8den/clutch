#!/usr/bin/env python3
"""
Sync Back Market trade-in payouts into the Clutch quote site.

Reads a CSV export of the "BM Quotes" tab of the Clutch Marketplace Lead Tracker
sheet, maps each row to the site's model / storage keys, and rewrites the
generated BM_PAYOUTS block in site/index.html. Nothing is deployed: review the
diff, commit, and merge like any other change.

Usage:
    python3 scripts/sync_bm_payouts.py path/to/bm_quotes.csv \
        [--sellcell sellcell.csv] [--site site/index.html] \
        [--report bm_sync_report.md] [--dry-run]

How the sheet maps to the site
- Only rows with Functional = Yes, Appearance/Screen = Good, Sides = Good (or "-")
  and, for phones, Carrier = Unlocked become base payouts. The site applies its
  own grade factors (Used 0.80, Cracked 0.47) and carrier penalties on top.
- Phones and iPads: key "<model> <storage>", e.g. "iPhone 16 Pro 256GB".
- MacBooks (Category "Laptop"): Storage holds "<RAM>GB/<SSD>", key e.g.
  "MacBook Pro 14in M4 16GB/512GB".
- Consoles: "<site model> <storage>" when the site offers more than one storage
  size for that console, otherwise just "<site model>" (same as the wizard).
- Consoles with several accessory rows use the standard bundle (1 controller,
  or 2 controllers + dock for Nintendo) over a "0 controllers" quote.
- "No offer" rows are reported, never written as a Back Market payout.
- Where Back Market gives no offer, the SellCell CSV (columns "Key",
  "SellCell payout ($)", "Date pulled"; Key is the site key, payout is the best
  Good-condition price) fills in. With no SellCell price either, the option
  goes in NOT_BOUGHT and the wizard says Clutch isn't buying it right now.
  An unquoted size the old price list pays above every quoted size of that
  model goes in NOT_BOUGHT too, so it can't overpay.
- Used and Cracked rows become GRADE_CAPS where Back Market pays less for that
  grade than the site's grade factor would: the wizard then prices that grade
  off Back Market's payout for it instead.
- Every other price in DEFAULT_CASHOUT is left alone.

The customer price in the report uses the site's own formula:
    round(max(payout - shipping, 0) * grade * carrier * 0.72)
"""
import argparse
import csv
import datetime
import json
import re
import sys
from pathlib import Path

BEGIN = "// ── BEGIN BM_PAYOUTS (generated by scripts/sync_bm_payouts.py, do not edit by hand) ──"
END = "// ── END BM_PAYOUTS ──"

MARGIN = 0.72  # must match getMargin() in site/index.html
GRADE_FACTOR = {"Flawless": 1.0, "Good": 1.0, "Used": 0.80, "Cracked": 0.47}
GRADE_ORDER = ["Cracked", "Used", "Good", "Flawless"]
SHIP_COST = {"iPhone": 9, "Samsung": 9, "iPad": 14, "MacBook": 14, "Gaming": 15}

# Back Market model name (lowercase) -> site model key
CONSOLE_MODELS = {
    "playstation 5 pro": "PS5 Pro",
    "playstation 5 standard": "PS5 Disc (Standard)",
    "playstation 5": "PS5 Disc (Standard)",
    "playstation 5 digital edition": "PS5 Digital",
    "playstation 5 slim": "PS5 Slim Disc",
    "playstation 5 slim digital edition": "PS5 Slim Digital",
    "playstation 4 pro": "PS4 Pro",
    "playstation 4 slim": "PS4 Slim",
    "playstation 4": "PS4",
    "xbox series x": "Xbox Series X",
    "xbox series s": "Xbox Series S",
    "xbox one x": "Xbox One X",
    "xbox one s": "Xbox One S",
    "xbox one": "Xbox One",
    "switch 2": "Nintendo Switch 2",
    "switch oled": "Nintendo Switch OLED",
    "switch lite": "Nintendo Switch Lite",
    # "switch" is left out on purpose: Back Market lists one "Switch", the site
    # splits it into "Nintendo Switch V2" and "Nintendo Switch (Original)".
    "3ds xl": "Nintendo 3DS XL",
    "2ds xl": "Nintendo 2DS XL",
    "steam deck oled": "Steam Deck OLED",
    "steam deck lcd": "Steam Deck LCD",
}
# Sheet model name -> site model name, where they differ
PHONE_ALIASES = {
    "Galaxy Z Fold6": "Galaxy Z Fold 6",
    "Galaxy Z Flip6": "Galaxy Z Flip 6",
}
# Preferred accessory bundle when a console has several Good quotes
ACCESSORY_PREF = ["1 controller", "2 controllers + dock", "2 or more controllers",
                  "memory card", "none", "0 controllers"]


def storage_label(gb):
    n = int(float(gb))
    return f"{n // 1000}TB" if n >= 1000 and n % 1000 == 0 else f"{n}GB"


def parse_js_object(src, name):
    """Pull "key": value pairs out of a `const NAME = { ... };` literal."""
    m = re.search(r"const\s+" + re.escape(name) + r"\s*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        sys.exit(f"Could not find const {name} in site file")
    body = m.group(1)
    out = {}
    for k, v in re.findall(r'"([^"]+)"\s*:\s*(\[[^\]]*\]|-?\d+(?:\.\d+)?)', body):
        out[k] = json.loads(v) if v.startswith("[") else float(v)
    return out


def parse_generated(src):
    if BEGIN not in src:
        return {}
    block = src.split(BEGIN, 1)[1].split(END, 1)[0].split("const SELLCELL_PAYOUTS", 1)[0]
    return {k: float(v) for k, v in re.findall(r'"([^"]+)"\s*:\s*(\d+(?:\.\d+)?)', block)}


def offer(payout, category, grade="Good"):
    return round(max(payout - SHIP_COST.get(category, 12), 0) * GRADE_FACTOR[grade] * MARGIN)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--sellcell", default=None)
    ap.add_argument("--site", default="site/index.html")
    ap.add_argument("--report", default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    site_path = Path(args.site)
    src = site_path.read_text(encoding="utf-8")
    base = parse_js_object(src, "DEFAULT_CASHOUT")
    storage_map = parse_js_object(src, "STORAGE_MAP")
    console_storage = parse_js_object(src, "CONSOLE_STORAGE")
    previous = parse_generated(src)

    rows = list(csv.DictReader(open(args.csv, newline="", encoding="utf-8")))
    candidates = {}   # key -> list of (accessory_rank, payout, row)
    other_grades = []  # (key, category, grade, bm_quote, row)
    unmapped, no_offer = [], []
    dates = set()

    for r in rows:
        model = (r.get("Model") or "").strip()
        if not model:
            continue
        cat_raw = (r.get("Category") or "").strip().lower()
        quote_raw = (r.get("Back Market quote ($)") or "").strip()
        acc = (r.get("Accessories") or "-").strip()
        screen = (r.get("Appearance / Screen") or "").strip().title()
        sides = (r.get("Sides (phones)") or "-").strip().title()
        carrier = (r.get("Carrier") or "-").strip().lower()
        functional = (r.get("Functional") or "Yes").strip().lower()
        desc = f"{model} {r.get('Storage (GB)')}GB, {acc}, {screen}/{sides}, {carrier}"
        if r.get("Date pulled"):
            dates.add(r["Date pulled"].strip())

        # Map to a site key
        key = category = None
        try:
            label = storage_label(r.get("Storage (GB)"))
        except (TypeError, ValueError):
            label = None
        model = PHONE_ALIASES.get(model, model)
        if cat_raw == "phone":
            category = "iPhone" if model.lower().startswith("iphone") else "Samsung"
            if model in storage_map and label in storage_map[model]:
                key = f"{model} {label}"
        elif cat_raw == "tablet":
            category = "iPad"
            if model in storage_map and label in storage_map[model]:
                key = f"{model} {label}"
        elif cat_raw == "laptop":
            # MacBook storage is "<RAM>GB/<SSD>", e.g. "16GB/512GB", as the site lists it
            category = "MacBook"
            cfg = (r.get("Storage (GB)") or "").strip()
            if model in storage_map and cfg in storage_map[model]:
                key = f"{model} {cfg}"
        elif cat_raw == "console":
            category = "Gaming"
            site_model = CONSOLE_MODELS.get(model.lower())
            opts = console_storage.get(site_model, []) if site_model else []
            if site_model and label in opts:
                key = f"{site_model} {label}" if len(opts) > 1 else site_model
        if not key:
            unmapped.append(desc)
            continue

        try:
            quote = float(quote_raw.replace("$", "").replace(",", ""))
        except ValueError:
            no_offer.append((key, desc, quote_raw or "blank"))
            continue
        if functional != "yes":
            continue
        if category in ("iPhone", "Samsung") and carrier != "unlocked":
            continue

        grades = [g for g in (screen, sides) if g in GRADE_FACTOR]
        worst = sorted(grades, key=GRADE_ORDER.index)[0] if grades else None
        if worst == "Good" and all(g == "Good" for g in grades):
            a = acc.lower()
            rank = ACCESSORY_PREF.index(a) if a in ACCESSORY_PREF else 0
            candidates.setdefault(key, []).append((rank, quote, desc, category))
        elif worst:
            other_grades.append((key, category, worst, quote, desc))

    payouts, meta = {}, {}
    for key, opts in candidates.items():
        opts.sort(key=lambda t: t[0])
        payouts[key] = int(round(opts[0][1]))
        meta[key] = opts[0]

    # Grade caps: Back Market's payout for a worse grade, where it is below
    # what the site's grade factor gives from the Good payout
    grade_best = {}
    for key, cat, grade, bm, desc in other_grades:
        if grade not in ("Used", "Cracked"):
            continue
        a = desc.split(", ")[1].lower() if ", " in desc else ""
        rank = ACCESSORY_PREF.index(a) if a in ACCESSORY_PREF else 0
        cur = grade_best.get((grade, key))
        if cur is None or rank < cur[0]:
            grade_best[(grade, key)] = (rank, int(round(bm)), cat, desc)
    grade_caps = {}
    for (grade, key), (_, bm, cat, desc) in grade_best.items():
        good = payouts.get(key)
        if good and bm < good * GRADE_FACTOR[grade]:
            grade_caps.setdefault(grade, {})[key] = bm

    # SellCell fallback and options the site stops buying
    sellcell, sc_dates = {}, set()
    if args.sellcell:
        for r in csv.DictReader(open(args.sellcell, newline="", encoding="utf-8")):
            k = (r.get("Key") or "").strip()
            v = (r.get("SellCell payout ($)") or "").strip().replace("$", "").replace(",", "")
            if not k:
                continue
            if r.get("Date pulled"):
                sc_dates.add(r["Date pulled"].strip())
            try:
                sellcell[k] = int(round(float(v)))
            except ValueError:
                sellcell[k] = None
    sc_payouts, not_bought = {}, {}
    for key, desc, _ in no_offer:
        if key in payouts:
            continue
        if sellcell.get(key):
            sc_payouts[key] = sellcell[key]
        else:
            not_bought[key] = ("Back Market gives no offer; SellCell has none"
                               if key in sellcell else
                               "Back Market gives no offer; no SellCell price on file")
    valid = {f"{m} {o}" for m, opts in storage_map.items() for o in opts}
    valid |= {(f"{m} {o}" if len(opts) > 1 else m) for m, opts in console_storage.items() for o in opts}
    for key, v in sellcell.items():
        if key not in valid:
            unmapped.append(f"SellCell row {key}")
            sc_payouts.pop(key, None)
            continue
        if v and key not in payouts and key not in sc_payouts:
            sc_payouts[key] = v

    pulled = max(dates) if dates else datetime.date.today().isoformat()
    # Report
    def old_value(key):
        if key in previous:
            return previous[key]
        if key in base:
            return base[key]
        # wizard falls back to the plain model key
        for m in sorted(base, key=len, reverse=True):
            if key.startswith(m + " "):
                return base[m]
        return None

    rep = [f"# Back Market payout sync ({pulled})", "",
           "| Site option | Old payout | New BM payout | Customer offer (Good, unlocked, shipped) | Your margin |",
           "|---|---:|---:|---:|---:|"]
    changed = 0
    for k in sorted(payouts):
        new = payouts[k]
        old = old_value(k)
        cat = meta[k][3]
        off = offer(new, cat)
        if old is None or int(old) != new:
            changed += 1
        old_s = f"${int(old)}" if old is not None else "none"
        rep.append(f"| {k} | {old_s} | ${new} | ${off} | {round((1 - off / new) * 100) if new else 0}% |")
    rep += ["", f"{changed} of {len(payouts)} payouts changed.", ""]

    flags = []
    for key, cat, grade, bm, desc in other_grades:
        p = payouts.get(key) or old_value(key)
        if not p:
            continue
        site = offer(p, cat, grade)
        if key in grade_caps.get(grade, {}):
            continue  # now priced off Back Market's payout for this grade
        if site >= bm * 0.8:  # under 20% margin on this grade
            flags.append(f"- {desc}: site offers ${site}, Back Market pays ${int(bm)}")
    if flags:
        rep += ["## Grades where the site's grade factor pays too much", ""] + flags + [""]
    if sc_payouts:
        rep += ["## Priced from SellCell (Back Market gives no offer or no quote yet)", "",
                "| Site option | Old payout | SellCell payout | Customer offer (Good, unlocked, shipped) |",
                "|---|---:|---:|---:|"]
        for k, v in sorted(sc_payouts.items()):
            old = old_value(k)
            cat = "iPad" if k.startswith("iPad") else ("Samsung" if k.startswith("Galaxy") else "Gaming")
            rep.append(f"| {k} | ${int(old or 0)} | ${v} | ${offer(v, cat)} |")
        rep.append("")
    if grade_caps:
        rep += ["## Grades now priced off Back Market's payout for that grade", ""]
        for g in sorted(grade_caps):
            for k, v in sorted(grade_caps[g].items()):
                cat = meta[k][3]
                rep.append(f"- {k}, {g}: Back Market pays ${v}; site offer was ${offer(payouts[k], cat, g)}, "
                           f"now ${round(max(v - SHIP_COST.get(cat, 12), 0) * MARGIN)}")
        rep.append("")
    # Site options on a quoted model that still fall back to the old model-level price
    fallbacks = []
    quoted_models = {}
    for k in payouts:
        for m in list(storage_map) + list(console_storage):
            if k.startswith(m + " "):
                quoted_models.setdefault(m, []).append(payouts[k])
    for m, vals in sorted(quoted_models.items()):
        opts = storage_map.get(m) or console_storage.get(m) or []
        missing = [o for o in opts if f"{m} {o}" not in payouts]
        for o in missing:
            fb = base.get(f"{m} {o}", base.get(m))
            k = f"{m} {o}"
            if k in sc_payouts or k in not_bought:
                continue
            if fb and fb > max(vals):
                not_bought[k] = f"no quote yet, and the old ${int(fb)} price was above every quoted size"
                continue
            fallbacks.append(f"- {k}: no quote yet, site uses ${int(fb or 0)}")
    if fallbacks:
        rep += ["## Sizes with no quote yet (still on the old model price)", ""] + fallbacks + [""]
    if unmapped:
        rep += ["## Sheet rows that don't match a site option", ""] + [f"- {d}" for d in unmapped] + [""]

    if not_bought:
        rep += ["## Now shown as not bought", ""]
        rep += [f"- {k}: {why}" for k, why in sorted(not_bought.items())] + [""]

    # Write the generated block
    lines = [BEGIN,
             f"// Back Market trade-in payouts (Good, unlocked, functional). Quotes pulled {pulled}.",
             "// Keys are \"<model> <storage>\" (phones, multi-storage consoles) or \"<model>\".",
             "const BM_PAYOUTS = {"]
    for k in sorted(payouts):
        lines.append(f'  {json.dumps(k)}:{payouts[k]},')
    lines += ["};"]
    sc_pulled = max(sc_dates) if sc_dates else pulled
    lines += [f"// SellCell best Good payout, used only where Back Market gives no offer. Pulled {sc_pulled}.",
              "const SELLCELL_PAYOUTS = {"]
    lines += [f'  {json.dumps(k)}:{v},' for k, v in sorted(sc_payouts.items())]
    lines += ["};",
              "// Options Clutch isn't buying right now: no Back Market or SellCell price.",
              "const NOT_BOUGHT = ["]
    lines += [f'  {json.dumps(k)},' for k in sorted(not_bought)]
    lines += ["];",
              "// Back Market's payout for a worse grade, where it is below payout x grade factor.",
              "const GRADE_CAPS = {"]
    for g in sorted(grade_caps):
        inner = ", ".join(f"{json.dumps(k)}:{v}" for k, v in sorted(grade_caps[g].items()))
        lines.append(f"  {g}:{{ {inner} }},")
    lines += ["};", END]
    block = "\n".join(lines)
    if BEGIN in src:
        new_src = src.split(BEGIN, 1)[0] + block + src.split(END, 1)[1]
    else:
        sys.exit("BM_PAYOUTS markers not found in site file; add them once by hand first.")

    report = "\n".join(rep)
    if args.report:
        Path(args.report).write_text(report, encoding="utf-8")
    print(report)
    if not args.dry_run:
        site_path.write_text(new_src, encoding="utf-8")
        print(f"\nWrote {len(payouts)} payouts to {site_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
